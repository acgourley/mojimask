function Icon(name, size = 16) {
  return `<svg class="ic" style="width:${size}px;height:${size}px" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name] || ""}</svg>`;
}
// <i data-ic="play"></i> in a page's own markup becomes the icon (data-size for another size)
function drawIcons(root = document) {
  for (const el of root.querySelectorAll("i[data-ic]")) el.outerHTML = Icon(el.dataset.ic, +el.dataset.size || 16);
}
// a slider shows how far along it is: --p is its value as a percentage (theme.css fills the track up to it)
function fillRange(el) {
  const lo = +el.min || 0, hi = el.max === "" ? 100 : +el.max;
  el.style.setProperty("--p", `${hi > lo ? ((+el.value - lo) / (hi - lo)) * 100 : 0}%`);
}
document.addEventListener("input", (e) => { if (e.target instanceof HTMLInputElement && e.target.type === "range") fillRange(e.target); }, true);
