//! `mm-pack notices APP ROOT NATIVE`: THIRD_PARTY_NOTICES.md and licenses/ for the native bundle
//! (Contents/Resources), from what is actually in it.
//!
//! - Rust crates: the normal (non-dev, non-build) dependency closure of mm-app and mm-cli for aarch64-apple-darwin
//!   (`cargo metadata`, offline), each crate's licence expression, and its own LICENSE*/COPYING*/NOTICE* files copied
//!   from the cargo registry to licenses/crates/<name>-<version>/. mojimask's own crates (mm-*) are AGPL-3.0
//!   (LICENSE).
//! - ONNX Runtime (linked statically by ort): MIT, with its ThirdPartyNotices: NATIVE/packaging/licenses/onnxruntime/
//!   (copied from the onnxruntime 1.31.1 wheel, the same upstream project; ort's prebuilt library ships none).
//! - Native libraries: every file `relocate` copied into Contents/Frameworks plus the Qt and GStreamer plugins in
//!   PlugIns/, grouped by the Homebrew formula they came from (NATIVE/dist/relocate.json's sources), with the
//!   formula's licence (FORMULA_LICENCES below: Homebrew's own metadata, written down so no network is needed) and
//!   its licence files from the Cellar. Qt and GLib ship none there: their LGPL texts are in licenses/ (LGPL-2.1,
//!   LGPL-3.0 with GPL-3.0, which LGPL-3.0 builds on).
//! - Models, fonts, pictures and the sample clip: the same rows as the Python app's THIRD_PARTY_NOTICES.md (copied
//!   from ROOT/THIRD_PARTY_NOTICES.md, so the two stay one source), with MIT texts for RetinaFace and OSNet.
//! Fails (exit 1) on a library whose formula has no licence entry, so a new dependency can't ship unlisted; prints
//! a one-line JSON summary either way. The output is what notices.py wrote, byte for byte, except two lines that
//! named the Python scripts: "Generated by `mm-pack notices` (`native/crates/mm-pack`)", and ICU's "its data trimmed
//! (`mm-pack trim-icu`)".

