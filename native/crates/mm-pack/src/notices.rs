fn licence_of(name: &str) -> Option<&'static str> {
    FORMULA_LICENCES.iter().find(|(n, _)| *n == name).map(|(_, l)| *l)
}

/// (formula name without "@NN", (Cellar folder, version)) from a path under /Cellar/ (`/Cellar/([^/]+)/([^/]+)/`).
fn formula(real: &str) -> (Option<String>, Option<(String, String)>) {
    let mut from = 0;
    while let Some(i) = real[from..].find("/Cellar/") {
        let s = from + i + "/Cellar/".len();
        let rest = &real[s..];
        let parts: Vec<&str> = rest.splitn(3, '/').collect();
        // both groups non-empty, and a '/' after the second
        if parts.len() == 3 && !parts[0].is_empty() && !parts[1].is_empty() {
            let folder = parts[0].to_string();
            let name = match folder.rfind('@') {
                Some(j) if j + 1 < folder.len() && folder[j + 1..].bytes().all(|b| b.is_ascii_digit()) => {
                    folder[..j].to_string()
                }
                _ => folder.clone(),
            };
            return (Some(name), Some((folder, parts[1].to_string())));
        }
        from = from + i + 1;
    }
    (None, None)
}

/// From `start` up to (not including) `end`, trailing whitespace cut, plus "\n".
fn section(md: &str, start: &str, end: &str) -> Result<String> {
    let i = md.find(start).with_context(|| format!("no {start:?} in THIRD_PARTY_NOTICES.md"))?;
    let j = md[i..].find(end).with_context(|| format!("no {end:?} in THIRD_PARTY_NOTICES.md"))? + i;
    Ok(format!("{}\n", md[i..j].trim_end()))
}

/// Case-insensitive "starts with one of" (the script's `re.match(r"(?i)(a|b|...)", f)`).
fn starts_ci(f: &str, pats: &[&str]) -> bool {
    let l = f.to_lowercase();
    pats.iter().any(|p| l.starts_with(p))
}

fn str_of(v: Option<&Value>) -> Option<String> {
    match v {
        Some(Value::Str(s)) => Some(s.clone()),
        _ => None,
    }
}

pub fn run(app: &str, root: &str, native: &str) -> Result<i32> {
    let here = join(native, "packaging"); // licenses/ beside the scripts
    let res = join(&join(app, "Contents"), "Resources");
    let lic = join(&res, "licenses");
    let _ = std::fs::remove_dir_all(&lic);
    std::fs::create_dir_all(&lic)?;
    let mut missing: Vec<String> = Vec::new();

    // -- standard texts
    let first = |pat: &str| glob(pat).into_iter().next();
    let std_texts: Vec<(&str, Option<String>)> = vec![
        ("AGPL-3.0.txt", Some(join(root, "LICENSE"))),
        ("GPL-3.0.txt", Some(join(&here, "licenses/GPL-3.0.txt"))),
        ("LGPL-2.1.txt", first("/opt/homebrew/Cellar/gstreamer/*/LICENSE")),
        ("LGPL-3.0.txt", first("/opt/homebrew/Cellar/gmp/*/COPYING.LESSERv3")),
        ("OFL-1.1-Nunito.txt", Some(join(root, "native/web/fonts/Nunito-OFL.txt"))),
        ("OFL-1.1-Inter.txt", Some(join(root, "native/web/fonts/Inter-OFL.txt"))),
    ];
    for (name, src) in std_texts {
        match src {
            Some(s) if !s.is_empty() && is_file(&s) => copy2(&s, &join(&lic, name))?,
            _ => missing.push(format!("{name}: not found")),
        }
    }
    // MIT texts for the models whose repos state MIT
    for (name, who) in [
        ("MIT-RetinaFace.txt", "2019 biubug6 (Pytorch_Retinaface)"),
        ("MIT-OSNet.txt", "2018 Kaiyang Zhou (deep-person-reid / torchreid)"),
    ] {
        std::fs::write(join(&lic, name), MIT.replace("{who}", who))?;
    }

    // -- crates
    let out = std::process::Command::new("cargo")
        .args(["metadata", "--format-version", "1", "--offline", "--filter-platform", "aarch64-apple-darwin"])
        .current_dir(native)
        .output()
        .context("running cargo metadata")?;
    if !out.status.success() {
        anyhow::bail!("cargo metadata failed: {}", String::from_utf8_lossy(&out.stderr));
    }
    let meta: serde_json::Value = serde_json::from_slice(&out.stdout)?;
    let s = |v: &serde_json::Value, k: &str| v.get(k).and_then(|x| x.as_str()).map(str::to_string);
    let packages = meta["packages"].as_array().context("cargo metadata: no packages")?;
    let pk: std::collections::HashMap<String, &serde_json::Value> =
        packages.iter().map(|p| (s(p, "id").unwrap_or_default(), p)).collect();
    let nodes: std::collections::HashMap<String, &serde_json::Value> = meta["resolve"]["nodes"]
        .as_array()
        .context("cargo metadata: no resolve")?
        .iter()
        .map(|n| (s(n, "id").unwrap_or_default(), n))
        .collect();
    let mut seen: HashSet<String> = HashSet::new();
    let mut stack: Vec<String> = packages
        .iter()
        .filter(|p| matches!(p["name"].as_str(), Some("mm-app") | Some("mm-cli")))
        .filter_map(|p| s(p, "id"))
        .collect();
    while let Some(i) = stack.pop() {
        if !seen.insert(i.clone()) {
            continue;
        }
        for d in nodes[&i]["deps"].as_array().into_iter().flatten() {
            let normal = d["dep_kinds"].as_array().into_iter().flatten().any(|k| k["kind"].is_null());
            if normal {
                stack.push(s(d, "pkg").unwrap_or_default());
            }
        }
    }
    let mut crates: Vec<&serde_json::Value> = seen.iter().map(|i| pk[i]).collect();
    let name_of = |p: &serde_json::Value| s(p, "name").unwrap_or_default();
    let ver_of = |p: &serde_json::Value| s(p, "version").unwrap_or_default();
    crates.sort_by(|a, b| (name_of(a), ver_of(a)).cmp(&(name_of(b), ver_of(b))));
    let ours: Vec<&serde_json::Value> = crates.iter().copied().filter(|p| name_of(p).starts_with("mm-")).collect();
    let theirs: Vec<&serde_json::Value> = crates.iter().copied().filter(|p| !name_of(p).starts_with("mm-")).collect();
    let mut crate_rows = Vec::new();
    for p in &theirs {
        let (name, version) = (name_of(p), ver_of(p));
        let d = dirname(&s(p, "manifest_path").unwrap_or_default());
        let files: Vec<String> = listdir(&d)?
            .into_iter()
            .filter(|f| starts_ci(f, &["licence", "license", "copying", "notice", "unlicense"]) && is_file(&join(&d, f)))
            .collect();
        let dest = join(&join(&lic, "crates"), &format!("{name}-{version}"));
        if !files.is_empty() {
            std::fs::create_dir_all(&dest)?;
            for f in &files {
                copy2(&join(&d, f), &join(&dest, f))?;
            }
        }
        // Python truthiness: a missing, null or empty licence counts as none
        let license = s(p, "license").filter(|x| !x.is_empty());
        let license_file = s(p, "license_file").filter(|x| !x.is_empty());
        if license.is_none() && license_file.is_none() {
            missing.push(format!("crate {name} {version}: no licence"));
        }
        let shown = license.or(s(p, "license_file")).unwrap_or_else(|| "None".into());
        let text = if files.is_empty() {
            "standard text (SPDX)".to_string()
        } else {
            format!("`crates/{name}-{version}/`")
        };
        crate_rows.push(format!("| {name} | {version} | {shown} | {text} |"));
    }

    // the Apache-2.0 text (SFace, Depth Anything): one crate's copy of the standard text
    let mut apache = glob(&join(&lic, "crates/*/LICENSE-APACHE"));
    apache.sort();
    if let Some(a) = apache.first() {
        copy2(a, &join(&lic, "Apache-2.0.txt"))?;
    } else {
        missing.push("Apache-2.0.txt: no crate ships LICENSE-APACHE".into());
    }

    // -- ONNX Runtime (static, through ort-sys)
    let ort = join(&here, "licenses/onnxruntime");
    std::fs::create_dir(join(&lic, "onnxruntime"))?;
    for f in ["LICENSE", "ThirdPartyNotices.txt"] {
        if is_file(&join(&ort, f)) {
            copy2(&join(&ort, f), &join(&join(&lic, "onnxruntime"), f))?;
        } else {
            missing.push(format!("onnxruntime {f}"));
        }
    }
    let ort_ver = crates.iter().find(|p| name_of(p) == "ort-sys").map(|p| ver_of(p)).unwrap_or_else(|| "?".into());

    // -- native libraries
    let reloc_path = join(native, "dist/relocate.json");
    let reloc = crate::json::parse(&std::fs::read_to_string(&reloc_path).with_context(|| format!("reading {reloc_path}"))?)?;
    type Key = (Option<String>, Option<(String, String)>);
    let mut by_formula: Vec<(Key, Vec<String>)> = Vec::new();
    let mut add = |k: Key, f: String| {
        if let Some(e) = by_formula.iter_mut().find(|(kk, _)| *kk == k) {
            e.1.push(f);
        } else {
            by_formula.push((k, vec![f]));
        }
    };
    if let Some(Value::Obj(kv)) = reloc.get("sources") {
        for (rel, real) in kv {
            let real = str_of(Some(real)).unwrap_or_default();
            add(formula(&real), rel.replace("Frameworks/", ""));
        }
    } else {
        anyhow::bail!("{reloc_path}: no sources");
    }
    for (kind, d) in [("gstreamer", "PlugIns/gstreamer"), ("qtbase", "PlugIns/platforms"), ("qtbase", "PlugIns/imageformats")] {
        let full = join(&join(app, "Contents"), d);
        let mut fs = listdir(&full)?;
        fs.sort();
        for f in fs {
            let real = if kind == "qtbase" {
                let g = glob(&format!("/opt/homebrew/share/qt/plugins/*/{f}"));
                realpath(g.first().with_context(|| format!("no Qt plugin {f} in /opt/homebrew/share/qt/plugins"))?)
            } else {
                realpath(&format!("/opt/homebrew/lib/gstreamer-1.0/{f}"))
            };
            add(formula(&real), format!("{d}/{f}"));
        }
    }
    // sorted by formula name (None as ""), stable
    by_formula.sort_by(|a, b| a.0 .0.clone().unwrap_or_default().cmp(&b.0 .0.clone().unwrap_or_default()));
    let mut lib_rows = Vec::new();
    for ((name, cell), files) in &by_formula {
        let lic_text = name.as_deref().and_then(licence_of);
        let Some(lic_text) = lic_text else {
            let n = name.clone().unwrap_or_else(|| "None".into());
            let head: Vec<String> = files.iter().take(3).cloned().collect();
            missing.push(format!("formula {n}: no licence entry ({})", py_repr_list(&head)));
            continue;
        };
        let name = name.clone().unwrap();
        let cell = cell.clone().unwrap();
        let cdir = format!("/opt/homebrew/Cellar/{}/{}", cell.0, cell.1);
        let texts: Vec<String> = listdir(&cdir)?
            .into_iter()
            .filter(|f| starts_ci(f, &["licen", "copying", "notice", "readme.ijg"]) && is_file(&join(&cdir, f)))
            .collect();
        if !texts.is_empty() {
            let dest = join(&join(&lic, "libraries"), &name);
            std::fs::create_dir_all(&dest)?;
            for f in &texts {
                copy2(&join(&cdir, f), &join(&dest, f))?;
            }
        }
        let where_ = if !texts.is_empty() {
            format!("`libraries/{name}/`")
        } else if name.starts_with("qt") {
            "`LGPL-3.0.txt`, `GPL-3.0.txt`".into()
        } else {
            "`LGPL-2.1.txt`".into()
        };
        let mut shown: Vec<String> = files
            .iter()
            .map(|f| match f.find(".framework") {
                Some(i) => basename(&f[..i]),
                None => basename(f),
            })
            .collect::<HashSet<_>>()
            .into_iter()
            .collect();
        shown.sort();
        lib_rows.push(format!("| {name} {} | {lic_text} | {} | {where_} |", cell.1, shown.join(", ")));
    }

    // -- models, fonts, pictures: the Python app's rows
    let py = std::fs::read_to_string(join(root, "THIRD_PARTY_NOTICES.md"))?;
    let models = section(&py, "## Models", "## Software")?;
    let pictures = section(&py, "## Fonts and pictures", "## mojimask's own licence")?;
    let ours_names: Vec<String> = ours.iter().map(|p| name_of(p)).collect();

    let md = format!(
        "# Third-party notices

mojimask's native Mac app bundles the software, models, fonts and pictures below. Each keeps its own licence; the
texts are in `licenses/` beside this file (`Contents/Resources/licenses`), and mojimask's own licence in `LICENSE`.
Generated by `mm-pack notices` (`native/crates/mm-pack`) from what the bundle contains.

{models}
## Software: native libraries (`Contents/Frameworks`, `Contents/PlugIns`)

Built by Homebrew; `Contents/MacOS/gst-plugin-scanner` is GStreamer's too. Every one is a separate dynamic library that can be replaced with a compatible build (what the
LGPL asks). Their sources: the Homebrew formula of the same name and version.

| library | licence | files | text in `licenses/` |
|---|---|---|---|
{lib_rows}

## Software: linked into the app (`Contents/MacOS`)

| component | licence | text in `licenses/` |
|---|---|---|
| ONNX Runtime (Microsoft; prebuilt static library through the `ort` crate, ort-sys {ort_ver}), with its own third-party notices | MIT | `onnxruntime/` |
| mojimask's own crates ({ours}) | AGPL-3.0-or-later | `AGPL-3.0.txt` |

### Rust crates ({n_theirs})

| crate | version | licence | text in `licenses/` |
|---|---|---|---|
{crate_rows}

{pictures}
## mojimask's own licence

mojimask is free software under the GNU Affero General Public License 3.0 (`LICENSE`), with no warranty. The app as a
whole is distributed on AGPL-3.0 terms: anyone who has it may get its complete source (this repository, with
`native/packaging/` for building it and `models/README.md` for the model files) and change and share it under the
same terms.
",
        lib_rows = lib_rows.join("\n"),
        ours = ours_names.join(", "),
        n_theirs = theirs.len(),
        crate_rows = crate_rows.join("\n"),
    );
    std::fs::write(join(&res, "THIRD_PARTY_NOTICES.md"), md)?;
    let n: usize = walk(&lic).iter().map(|(_, fs)| fs.len()).sum();
    let summary = Value::Obj(vec![
        ("crates".into(), Value::Int(theirs.len() as i64)),
        ("library_groups".into(), Value::Int(lib_rows.len() as i64)),
        ("licence_files".into(), Value::Int(n as i64)),
        ("missing".into(), Value::Arr(missing.iter().cloned().map(Value::Str).collect())),
    ]);
    println!("{}", dumps(&summary));
    Ok(if missing.is_empty() { 0 } else { 1 })
}
